import * as v from 'valibot';
import { rawOrderSchema } from '../schema';
import { MOCK_OFFERS } from '../../offer/api/'; // adjust path to your mock offers file

type RawOrder = v.InferOutput<typeof rawOrderSchema>;

type ApiResponseRawOrder = {
   checkoutForms: RawOrder[];
   count: number;
   totalCount: number;
};

type FetchOrdersOptions = {
   pagesLimit?: number;
   pageSize?: number;
   sort?:
      | 'updatedAt'
      | '-updatedAt'
      | 'lineItems.boughtAt'
      | '-lineItems.boughtAt';
   updatedAtGte?: Date;
   updatedAtLte?: Date;
   status?: 'READY_FOR_PROCESSING';
};

type AuthOptions = {
   userAgent: string;
   accessToken: string;
};

const MOCK_ORDERS_COUNT = 120;
const BASE_TIME = new Date().getTime();
const HOUR = 60 * 60 * 1000;

const STATUSES: RawOrder['status'][] = [
   'READY_FOR_PROCESSING',
   'READY_FOR_PROCESSING',
   'READY_FOR_PROCESSING',
   'READY_FOR_PROCESSING',
   'BOUGHT',
   'FILLED_IN',
   'CANCELLED',
];

const FULFILLMENT: RawOrder['fulfillment']['status'][] = [
   'NEW',
   'PROCESSING',
   'SENT',
   'READY_FOR_SHIPMENT',
];

const buildOrder = (i: number): RawOrder => {
   const n = i + 1;
   const status = STATUSES[i % STATUSES.length];
   const isPickup = i % 4 === 0;

   // Line items reference offers generated by the mock fetchOffers
   const lineItems = Array.from({ length: (i % 3) + 1 }, (_, j) => {
      const offer = MOCK_OFFERS[(i + j * 7) % MOCK_OFFERS.length];
      const quantity = ((i + j) % 3) + 1;
      const unitPrice = 19.99 + ((i + j * 5) % 10) * 10;

      return {
         id: `line-${n}-${j + 1}`,
         offer: { id: offer.id, name: offer.name },
         quantity,
         price: { amount: unitPrice.toFixed(2), currency: 'PLN' },
      };
   });

   const itemsTotal = lineItems.reduce(
      (sum, item) => sum + Number(item.price.amount) * item.quantity,
      0,
   );
   const deliveryCost = isPickup ? 8.99 : 12.99;
   const online = i % 5 !== 0;

   return {
      id: `00000000-0000-4000-8000-${String(n).padStart(12, '0')}`,

      buyer: {
         id: `buyer-${n}`,
         email: `buyer${n}@example.com`,
         login: `buyer_${n}`,
         firstName: 'Jan',
         lastName: `Kowalski${n}`,
         companyName: null,
         guest: false,
         personalIdentity: null,
         phoneNumber: '+48500000000',
         address: {
            street: `Testowa ${n}`,
            city: 'Warszawa',
            postCode: '00-001',
            countryCode: 'PL',
         },
      },

      payment: {
         type: online ? 'ONLINE' : 'CASH_ON_DELIVERY',
         paidAmount: online
            ? {
                 amount: (itemsTotal + deliveryCost).toFixed(2),
                 currency: 'PLN',
              }
            : null,
      },

      lineItems,
      status,

      fulfillment: {
         status: status === 'READY_FOR_PROCESSING' ? FULFILLMENT[i % 4] : 'NEW',
      },

      delivery: {
         address: {
            firstName: 'Jan',
            lastName: `Kowalski${n}`,
            street: `Testowa ${n}`,
            city: 'Warszawa',
            zipCode: '00-001',
            countryCode: 'PL',
            companyName: null,
            phoneNumber: '+48500000000',
         },
         method: {
            id: isPickup ? 'pickup-method' : 'courier-method',
            name: isPickup ? 'Allegro Paczkomaty InPost' : 'Allegro Kurier DPD',
         },
         cost: { amount: deliveryCost.toFixed(2), currency: 'PLN' },
         pickupPoint: isPickup
            ? {
                 id: `WAW${n}`,
                 name: `Paczkomat WAW${n}`,
                 description: 'Przy wejściu do sklepu',
                 address: {
                    street: 'Marszałkowska 1',
                    zipCode: '00-002',
                    city: 'Warszawa',
                    countryCode: 'PL',
                 },
              }
            : null,
         calculatedNumberOfPackages: 1,
      },

      invoice: i % 6 === 0 ? { required: true } : null,

      summary: {
         totalToPay: {
            amount: (itemsTotal + deliveryCost).toFixed(2),
            currency: 'PLN',
         },
      },

      // Newer orders have a higher index-free timestamp: order #1 is the newest
      updatedAt: new Date(BASE_TIME - i * 1 * HOUR).toISOString(),
   };
};

const MOCK_ORDERS: RawOrder[] = Array.from(
   { length: MOCK_ORDERS_COUNT },
   (_, i) => buildOrder(i),
);

const delay = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms));

export async function fetchOrders(
   _auth: AuthOptions,
   options?: FetchOrdersOptions,
): Promise<ApiResponseRawOrder> {
   await delay(300);

   const pagesLimit = options?.pagesLimit ?? Infinity;
   const pageSize = options?.pageSize ?? 100;

   let orders = MOCK_ORDERS;

   if (options?.status) {
      orders = orders.filter((o) => o.status === options.status);
   }
   if (options?.updatedAtGte) {
      const gte = options.updatedAtGte.getTime();
      orders = orders.filter((o) => new Date(o.updatedAt).getTime() >= gte);
   }
   if (options?.updatedAtLte) {
      const lte = options.updatedAtLte.getTime();
      orders = orders.filter((o) => new Date(o.updatedAt).getTime() <= lte);
   }

   if (options?.sort) {
      const direction = options.sort.startsWith('-') ? -1 : 1;
      // lineItems.boughtAt isn't in the schema, so updatedAt is used for both
      orders = [...orders].sort(
         (a, b) =>
            direction *
            (new Date(a.updatedAt).getTime() - new Date(b.updatedAt).getTime()),
      );
   }

   const totalCount = orders.length;
   const page = orders.slice(0, pagesLimit * pageSize);

   return {
      checkoutForms: page,
      count: page.length,
      totalCount,
   };
}
